import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await mkdir('test-results',{recursive:true});
try{
 await page.goto('http://127.0.0.1:3000/');
 await page.getByRole('heading',{name:'What are we going to KawTeam today?',exact:true}).waitFor({timeout:10000});
 await page.locator('button[aria-label="Choose project"]:not(:disabled)').waitFor();
 for(const selector of ['.flow-demo-pill','.chat-compose-footnote','.chat-quick-prompts','.chat-integration-note'])assert.equal(await page.locator(selector).count(),0);
 assert.equal(await page.getByRole('button',{name:'Assistant settings',exact:true}).count(),0);
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 const nav=page.locator('#flow-navigation');
 await nav.getByRole('button',{name:'Overview',exact:true}).click();
 if(await nav.locator('[data-notification="approvals"]').count())assert.ok(Number(await nav.locator('[data-notification="approvals"]').innerText())>0);
 assert.ok(Number(await nav.locator('[data-notification="calendar"]').innerText())>0);
 await nav.getByRole('link',{name:/Recent Activity/}).click();
 await page.waitForURL(/\/overview\/activity/);
 assert.equal(await nav.evaluate(e=>e.inert),false,'Sidebar collapsed on navigation');
 assert.equal(await page.getByRole('navigation',{name:'Overview sections',exact:true}).count(),0);
 assert.equal(await page.getByRole('button',{name:/View activity: Your brief, understood/}).count(),0);
 await nav.getByRole('link',{name:/Approval/}).click();
 await page.getByRole('button',{name:'Approval Needed',exact:true}).waitFor();
 await page.getByRole('button',{name:'Approved',exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'All checkpoints',exact:true}).count(),0);
 if(await page.getByRole('button',{name:/Review supplier decision:/}).count()){
 await page.getByRole('button',{name:/Review supplier decision:/}).first().click();
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('link',{name:'Open in project',exact:true}).waitFor();
 await dialog.getByRole('button',{name:'Approved',exact:true}).waitFor();
 assert.equal(await dialog.getByText('Exact message approval',{exact:true}).count(),0);
 assert.equal(await dialog.getByText('Supplier conversation',{exact:true}).count(),0);
 assert.equal(await dialog.getByRole('link',{name:'Open full conversation',exact:true}).count(),0);
 assert.equal(await dialog.locator('.flow-draft-preview').count(),0);
 await page.screenshot({path:'test-results/refinement-approval-desktop.png',fullPage:true});
 await dialog.getByRole('button',{name:'Close',exact:true}).click();
 }else await page.getByText('No approvals waiting',{exact:true}).waitFor();
 await nav.getByRole('link',{name:/Calendar/}).click();
 await page.getByRole('region',{name:'Upcoming dates',exact:true}).waitFor();
 await page.getByRole('region',{name:'Past dates',exact:true}).waitFor();
 await page.locator('.kt-calendar .scheduled-day button').first().waitFor();
 assert.equal(await page.locator('.kt-calendar .scheduled-day button').first().evaluate(e=>getComputedStyle(e,'::after').backgroundColor),'rgb(209, 66, 66)');
 await page.locator('.kt-calendar .rdp-button_next').click();
 await page.getByRole('region',{name:'Upcoming dates',exact:true}).getByText('No upcoming dates in November 2026.',{exact:true}).waitFor();
 assert.equal(await page.locator('.agenda-item').count(),0);
 await page.locator('.kt-calendar .rdp-button_previous').click();
 await page.getByRole('region',{name:'Upcoming dates',exact:true}).getByText('Tech Night',{exact:true}).waitFor();
 await page.screenshot({path:'test-results/refinement-calendar-desktop.png',fullPage:true});
 await nav.getByRole('link',{name:'Chat',exact:true}).click();
 await page.waitForURL('http://127.0.0.1:3000/');
 assert.equal(await nav.evaluate(e=>e.inert),false);
 await page.getByRole('button',{name:'Close navigation',exact:true}).click();
 await page.waitForTimeout(500);
 await page.screenshot({path:'test-results/refinement-chat-desktop.png',fullPage:true});
 for(const width of [390,768,1280,1440]){await page.setViewportSize({width,height:900});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Chat overflow ${width}`);}
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'test-results/refinement-chat-mobile.png',fullPage:true});
 await page.goto('http://127.0.0.1:3000/overview/calendar');
 await page.getByRole('heading',{name:'Your schedule',exact:true}).waitFor();
 await page.getByRole('region',{name:'Upcoming dates',exact:true}).getByText('Tech Night',{exact:true}).waitFor();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Calendar mobile overflow');
 await page.screenshot({path:'test-results/refinement-calendar-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);console.log('PASS: simplified chat, persistent sidebar, notification counts, milestones, concise approval and month-scoped calendar.');
}catch(error){await page.screenshot({path:'test-results/refinement-failure.png',fullPage:true});throw error;}finally{await browser.close();}
